def outline(im):
    a = np.asarray(im)[:, :, 3] > 0; h, w = a.shape; px = im.load()
    for y in range(h):
        for x in range(w):
            if not a[y, x] and any(0 <= y + dy < h and 0 <= x + dx < w and a[y + dy, x + dx] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                px[x, y] = INK
    return im
